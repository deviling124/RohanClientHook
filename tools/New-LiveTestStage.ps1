#requires -Version 7
<#
Stages a LIVE TEST of the encrypted channel in a new folder. It deploys nothing and touches no
running server, game folder or git state:

  bin\LiveTest\<stamp>\server\   Hero4Hook.dll (current build), TEST_ONLY_server_identity.private,
                                 mapconfig snippet
  bin\LiveTest\<stamp>\client\   novaclient.dll built with the TEST public key pinned, novaclient.ini
  bin\LiveTest\<stamp>\README.txt  exact steps, what to look for, how to roll back

The key is a THROWAWAY test key. The test public key is baked only into the staged client DLL
(via a temporary, git-ignored PinnedKeys.generated.h that this script removes again), so the
committed sources keep the empty placeholder.
#>
[CmdletBinding()]
param(
    [string]$MapServRepo = (Join-Path (Split-Path $PSScriptRoot -Parent | Split-Path -Parent) 'RohanMapServ_Hook'),
    # Reuse a throwaway key that is already installed on the test server: the staged client pins ITS public
    # half (read from the private blob, never printed) and the private file is not copied again, so the
    # server only needs the new Hero4Hook.dll.
    [string]$ExistingPrivateKey = '',
    # TEST BUILD: compile BOTH DLLs with a short re-key interval (frames per direction) so the ratchet can be
    # watched live in minutes. These builds use a different protocol version byte, so they never negotiate with
    # a normal build (they just stay plaintext). Never deploy them outside the test.
    [int]$TestRatchetInterval = 0
)
$ErrorActionPreference = 'Stop'
$clientRepo = Split-Path $PSScriptRoot -Parent
$vcvars = 'C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvarsall.bat'
$keygen = Join-Path $MapServRepo '.tools\nova-keygen\NovaChannelKeyGen.exe'
$serverDll = Join-Path $MapServRepo 'bin\Release\Hero4Hook.dll'
foreach ($path in $vcvars, $keygen, $serverDll) { if (-not (Test-Path $path)) { throw "Missing: $path (build it first)" } }

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
if ($TestRatchetInterval -gt 0) { $stamp += "-ratchet$TestRatchetInterval" }
$stage = Join-Path $clientRepo "bin\LiveTest\$stamp"
$serverDir = Join-Path $stage 'server'; $clientDir = Join-Path $stage 'client'
New-Item -ItemType Directory -Force $serverDir, $clientDir | Out-Null

# 1. Throwaway identity key (private file is owner-only and stays in the server folder).
if ($ExistingPrivateKey) {
    # A CNG ECCPRIVATE_BLOB is: 8-byte header, X (32), Y (32), d (32). Only X||Y (public) is used here.
    $blob = [IO.File]::ReadAllBytes($ExistingPrivateKey)
    if ($blob.Length -ne 104) { throw 'Unexpected private key blob size.' }
    $bytes = $blob[8..71] | ForEach-Object { $_.ToString('X2') }
    Remove-Variable blob
    $privateNote = 'reused: the server already has this key; the private file is NOT in this folder'
} else {
    $privateFile = Join-Path $serverDir 'TEST_ONLY_server_identity.private'
    $keyOutput = & $keygen $privateFile 2>$null
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $privateFile)) { throw 'Key generation failed.' }
    $bytes = [regex]::Matches(($keyOutput -join "`n"), '0x([0-9A-Fa-f]{2})') | ForEach-Object { $_.Groups[1].Value }
    $privateNote = 'new throwaway key: copy server\TEST_ONLY_server_identity.private to the server host'
}
if ($bytes.Count -ne 64) { throw "Expected 64 public key bytes, got $($bytes.Count)." }

# 2. Bake the TEST public key into a staged client DLL only.
$generated = Join-Path $clientRepo 'src\ClientGuard\PinnedKeys.generated.h'
$initializer = ($bytes | ForEach-Object { "0x$_" }) -join ', '
@"
// TEST ONLY: generated by tools\New-LiveTestStage.ps1. Do not keep or ship.
#pragma once
#include "../../shared/NovaChannel.h"
namespace ClientGuard {
inline constexpr std::size_t PinnedKeyCount = 1;
inline const NovaChannel::PublicKey PinnedKeys[1] = { { { $initializer } } };
} // namespace ClientGuard
"@ | Set-Content -Encoding ascii $generated
try {
    # A trailing backslash inside quotes would escape the quote, so double it.
    $outDir = $clientDir + '\\'
    $intDir = (Join-Path $stage 'obj') + '\\'
    # cl.exe reads the CL environment variable, which is how the test interval reaches the compiler
    # without touching the project file.
    if ($TestRatchetInterval -gt 0) { $env:CL = "/DNOVA_TEST_RATCHET_INTERVAL=$TestRatchetInterval" }
    $cmd = "call `"$vcvars`" x86 >nul 2>&1 && msbuild `"$clientRepo\RohanClientHook.vcxproj`" /p:Configuration=Release /p:Platform=Win32 /p:OutDir=`"$outDir`" /p:IntDir=`"$intDir`" /m:1 /nr:false /nologo /verbosity:minimal"
    cmd /c $cmd
    if ($LASTEXITCODE -ne 0) { throw 'Client DLL build failed.' }
    if ($TestRatchetInterval -gt 0) {
        # Build the SERVER DLL with the same interval into this stage (never into the normal bin\Release).
        $serverOut = $serverDir + '\\'
        $serverInt = (Join-Path $stage 'obj-server') + '\\'
        $scmd = "call `"$vcvars`" x86 >nul 2>&1 && msbuild `"$MapServRepo\Hero4Hook.vcxproj`" /p:Configuration=Release /p:Platform=Win32 /p:OutDir=`"$serverOut`" /p:IntDir=`"$serverInt`" /m:1 /nr:false /nologo /verbosity:minimal"
        cmd /c $scmd
        if ($LASTEXITCODE -ne 0) { throw 'Server DLL test build failed.' }
        # That project copies the repo's mapconfig.ini beside the DLL; remove it so it can never be copied over a live one.
        Get-ChildItem $serverDir -File | Where-Object { $_.Name -notin 'Hero4Hook.dll' -and $_.Name -notlike '*.private' } | Remove-Item -Force
        Remove-Item (Join-Path $stage 'obj-server') -Recurse -Force -ErrorAction SilentlyContinue
    }
} finally {
    Remove-Item Env:\CL -ErrorAction SilentlyContinue
    Remove-Item $generated -Force -ErrorAction SilentlyContinue   # the committed sources keep the placeholder
}
Get-ChildItem $clientDir -Exclude 'novaclient.dll' | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
Remove-Item (Join-Path $stage 'obj') -Recurse -Force -ErrorAction SilentlyContinue

# 3. Server pieces and the two ini files.
if ($TestRatchetInterval -le 0) { Copy-Item $serverDll (Join-Path $serverDir 'Hero4Hook.dll') }
@'
; Add this section to the TEST server's mapconfig.ini (next to Hero4Hook.dll), then restart MapTH.
; Set identity_file to where you put TEST_ONLY_server_identity.private on the server host.
[client_guard]
mode=audit
identity_file=TEST_ONLY_server_identity.private
'@ | Set-Content -Encoding ascii (Join-Path $serverDir 'mapconfig.client_guard.snippet.ini')
@'
[client_guard]
mode=audit
'@ | Set-Content -Encoding ascii (Join-Path $clientDir 'novaclient.ini')

$hashes = Get-ChildItem $serverDir, $clientDir -File | Where-Object { $_.Name -notlike '*.private' } |
    ForEach-Object { '{0}  {1}' -f (Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLower(), $_.FullName.Substring($stage.Length + 1) }
$hashes | Set-Content -Encoding ascii (Join-Path $stage 'SHA256.txt')

@"
LIVE TEST OF THE ENCRYPTED CHANNEL  (staged $stamp)
Key: $privateNote
=====================================================
Nothing here is deployed. You copy files yourself, on a TEST server and the TEST client copy only.

BEFORE YOU START
  * Back up the server's current Hero4Hook.dll and mapconfig.ini, and the client's novaclient.dll.
  * A MapTH restart disconnects everyone on it. Use a test instance or an agreed quiet time.
  * The private key file here is a THROWAWAY test key. Delete it (and this folder) when finished.

SERVER (on the host that runs MapTH + Hero4Hook)
  1. Copy server\Hero4Hook.dll over the server's Hero4Hook.dll (after backing it up).
  2. Copy server\TEST_ONLY_server_identity.private to the server host (keep it off shared folders).
  3. Add server\mapconfig.client_guard.snippet.ini to the server's mapconfig.ini; fix identity_file.
  4. Restart MapTH.  The console must show:
       [ClientGuard] client guard: mode=audit, hooks attached (offer set on the stock key frame)
     If it says "disabled" or "missing or invalid", read the reason on that line.

CLIENT (the TEST client copy only, e.g. NovaROHAN-Launcher-Test\client)
  1. Back up novaclient.dll, then copy client\novaclient.dll and client\novaclient.ini beside it.
  2. Start the client as usual. novaclient.log must end with:
       client guard: mode=audit, hooks attached
  3. Log in and play for a few minutes: move, chat, open the inventory, a kiosk, change map.

HOW TO TELL IT IS WORKING
  * Server console / Hero4Hook_clientguard.log: no "channel: ... rejected" lines.
  * Game behaves exactly as before (that is the main pass condition).
  * With the client running I can attach a read-only trace (Frida): the 8-byte keepalive that was 12
    bytes on the wire (4 header + 8) becomes 28 bytes (4 + 8 + 16 tag), and bodies look random.
  * To check the fallback: set the client's novaclient.ini to mode=disabled, restart the client, and
    confirm it still plays on the same server in plaintext.

IF ANYTHING GOES WRONG
  * Client: delete novaclient.ini (or set mode=disabled) and restore the backed-up novaclient.dll.
  * Server: set [client_guard] mode=disabled (or remove the section), restore Hero4Hook.dll, restart.
  * A failed channel ends that one connection (the game shows a disconnect). Note the message in
    novaclient.log / Hero4Hook_clientguard.log and send it to me.

KNOWN LIMITS OF THIS TEST BUILD
  * audit only (enforce is not available); the Gate is unaffected because it never takes the offer.
  * No re-keying, no attestation. Opcodes 0x3F01-0x3F04 are placeholders: if the real server or the
    Gate uses any of them, the log will show it.
"@ | Set-Content -Encoding ascii (Join-Path $stage 'README.txt')

if ($TestRatchetInterval -gt 0) {
    Add-Content -Encoding ascii (Join-Path $stage 'README.txt') @"

*** SHORT-INTERVAL RE-KEY TEST BUILD (interval = $TestRatchetInterval frames per direction) ***
  * BOTH client\novaclient.dll and server\Hero4Hook.dll in this folder must be installed together. They use
    protocol version byte 0xE2, so they only negotiate with each other (a normal build stays plaintext).
  * The idle keepalive is about 1 frame/second, so the first re-key happens after roughly $TestRatchetInterval seconds
    and then every $TestRatchetInterval seconds. Stay logged in for at least $([int]($TestRatchetInterval * 2 / 60) + 1) minutes (two boundaries: one proves it, a second confirms it repeats), moving and chatting too.
  * PASS: no disconnect, the game keeps working across the boundaries, no 'channel:' line on the server console.
  * AFTER THE TEST put the NORMAL DLLs back (bin\LiveTest\<normal stage>\ ...), not these.
"@
}
Write-Host "Staged: $stage"
Get-ChildItem $stage -Recurse -File | ForEach-Object { '  ' + $_.FullName.Substring($stage.Length + 1) + '  (' + $_.Length + ' bytes)' }
